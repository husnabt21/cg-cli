import { PostService } from './service';
import { requireAuth, handleError } from './middleware';

const service = new PostService();

export function createPostHandler(req: any, res: any): void {
  try {
    requireAuth(req);
    const record = service.create(req.body);
    res.status(201).json(record);
  } catch (err) {
    handleError(err, res);
  }
}

export function getPostHandler(req: any, res: any): void {
  try {
    requireAuth(req);
    res.json(service.get(req.params.id));
  } catch (err) {
    handleError(err, res);
  }
}

export function renamePostHandler(req: any, res: any): void {
  try {
    requireAuth(req);
    res.json(service.rename(req.params.id, req.body.name));
  } catch (err) {
    handleError(err, res);
  }
}

export function deletePostHandler(req: any, res: any): void {
  try {
    requireAuth(req);
    service.remove(req.params.id);
    res.status(204).json(null);
  } catch (err) {
    handleError(err, res);
  }
}

export const routes = [
  { method: 'POST', path: '/posts', handler: createPostHandler },
  { method: 'GET', path: '/posts/:id', handler: getPostHandler },
  { method: 'PUT', path: '/posts/:id', handler: renamePostHandler },
  { method: 'DELETE', path: '/posts/:id', handler: deletePostHandler },
];
